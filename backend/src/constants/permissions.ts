import { ROLES, UserRole } from './roles';

export const PERMISSIONS = {
  // User Management
  USER_READ: 'USER_READ',
  USER_UPDATE: 'USER_UPDATE',
  USER_DELETE: 'USER_DELETE',

  // Admin & Onboarding
  ADMIN_INVITE: 'ADMIN_INVITE',
  SELLER_KYC_REVIEW: 'SELLER_KYC_REVIEW',
  SELLER_KYC_SUBMIT: 'SELLER_KYC_SUBMIT',

  // Catalog
  CATEGORY_MANAGE: 'CATEGORY_MANAGE',
  PRODUCT_CREATE: 'PRODUCT_CREATE',
  PRODUCT_UPDATE: 'PRODUCT_UPDATE',
  PRODUCT_DELETE: 'PRODUCT_DELETE',
  PRODUCT_APPROVE: 'PRODUCT_APPROVE',
  PRODUCT_READ: 'PRODUCT_READ',

  // Inventory
  INVENTORY_READ: 'INVENTORY_READ',
  INVENTORY_MANAGE: 'INVENTORY_MANAGE',
  INVENTORY_ADJUST: 'INVENTORY_ADJUST',

  // Cart
  CART_MANAGE: 'CART_MANAGE',

  // Orders
  ORDER_CREATE: 'ORDER_CREATE',
  ORDER_READ_OWN: 'ORDER_READ_OWN',
  ORDER_READ_ALL: 'ORDER_READ_ALL',
  ORDER_UPDATE_STATUS: 'ORDER_UPDATE_STATUS',
  ORDER_CANCEL: 'ORDER_CANCEL',

  // Audit Logs
  AUDIT_LOG_READ: 'AUDIT_LOG_READ',
} as const;

export type Permission = (typeof PERMISSIONS)[keyof typeof PERMISSIONS];

export const ROLE_PERMISSIONS: Record<UserRole, Permission[]> = {
  [ROLES.SUPER_ADMIN]: Object.values(PERMISSIONS),
  [ROLES.ADMIN]: [
    PERMISSIONS.USER_READ,
    PERMISSIONS.USER_UPDATE,
    PERMISSIONS.ADMIN_INVITE,
    PERMISSIONS.SELLER_KYC_REVIEW,
    PERMISSIONS.CATEGORY_MANAGE,
    PERMISSIONS.PRODUCT_CREATE,
    PERMISSIONS.PRODUCT_UPDATE,
    PERMISSIONS.PRODUCT_DELETE,
    PERMISSIONS.PRODUCT_APPROVE,
    PERMISSIONS.PRODUCT_READ,
    PERMISSIONS.INVENTORY_READ,
    PERMISSIONS.INVENTORY_MANAGE,
    PERMISSIONS.INVENTORY_ADJUST,
    PERMISSIONS.ORDER_READ_ALL,
    PERMISSIONS.ORDER_UPDATE_STATUS,
    PERMISSIONS.ORDER_CANCEL,
    PERMISSIONS.AUDIT_LOG_READ,
  ],
  [ROLES.SELLER]: [
    PERMISSIONS.SELLER_KYC_SUBMIT,
    PERMISSIONS.PRODUCT_CREATE,
    PERMISSIONS.PRODUCT_UPDATE,
    PERMISSIONS.PRODUCT_READ,
    PERMISSIONS.INVENTORY_READ,
    PERMISSIONS.INVENTORY_MANAGE,
    PERMISSIONS.ORDER_READ_OWN,
    PERMISSIONS.ORDER_UPDATE_STATUS,
  ],
  [ROLES.BUYER]: [
    PERMISSIONS.PRODUCT_READ,
    PERMISSIONS.CART_MANAGE,
    PERMISSIONS.ORDER_CREATE,
    PERMISSIONS.ORDER_READ_OWN,
    PERMISSIONS.ORDER_CANCEL,
  ],
};

export const hasPermission = (role: UserRole, permission: Permission): boolean => {
  const permissions = ROLE_PERMISSIONS[role];
  return !!permissions && permissions.includes(permission);
};
